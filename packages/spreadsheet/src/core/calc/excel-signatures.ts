const fromFifth = (index: number): boolean => index >= 4;

const letName = (index: number, count: number): boolean => index % 2 === 0 && index < count - 1;

const pivotPairs = (count: number): boolean => count === 3 || count % 2 === 0;

const odd = (count: number): boolean => count % 2 === 1;

const SHAPED: readonly (readonly [string, CallSignature])[] = [
  ['AGGREGATE', { min: 3, max: 254, referenceAt: fromFifth }],
  ['AREAS', { min: 1, max: 1, referenceAt: firstArgument }],
  ['CELL', { min: 1, max: 2, referenceAt: secondArgument }],
  ['FORMULATEXT', { min: 1, max: 1, referenceAt: firstArgument }],
  ['GETPIVOTDATA', { min: 2, max: 254, counts: pivotPairs }],
  ['ISFORMULA', { min: 1, max: 1, referenceAt: firstArgument }],
  ['LET', { min: 3, max: 253, counts: odd, namesAt: letName, givesReference: true }],
  ['PHONETIC', { min: 1, max: 1, referenceAt: firstArgument }],
  ['RANK.AVG', { min: 2, max: 3, referenceAt: secondArgument }],
];

const EXCEL_SIGNATURES: ReadonlyMap<string, CallSignature> = new Map<string, CallSignature>([
  ...COUNTED.flatMap(([min, max, names]) =>
    names.map((name): [string, CallSignature] => [name, { min, max }]),
  ),
  ...DATABASE.map((name): [string, CallSignature] => [
    name,
    { min: 3, max: 3, referenceAt: firstArgument },
  ]),
  ...SHAPED,
]);

export const signaturesOf =
  (functions: FunctionRegistry): SignatureOf =>
  (name) =>
    functions.get(name) ?? EXCEL_SIGNATURES.get(name.toUpperCase());
